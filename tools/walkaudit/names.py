"""Generate WALK's machine-readable anchor handoff from canonical root NAMES.md.

Never creates runtime SpawnLocations or enables unsupported teleports. --check detects
drift without changing files; NAMES.md remains authoritative.
"""
import argparse
import json
from pathlib import Path
import re

ROOT=Path(__file__).resolve().parents[2]


def outputs():
    rows=[]
    for line in (ROOT/'NAMES.md').read_text().splitlines():
        if not line.startswith('| SC-'): continue
        cells=[cell.strip() for cell in line.strip('|').split('|')]
        if len(cells)!=5: raise ValueError('Canonical spawn row must have five cells')
        spawn,district,plaza,coordinate,availability=cells
        match=re.fullmatch(r'\((-?[\d.]+),\s*(-?[\d.]+),\s*(-?[\d.]+)\)',coordinate)
        if not match: raise ValueError('Invalid canonical coordinates')
        x,y,z=map(float,match.groups())
        built=availability.startswith('Built plaza;')
        if not built and 'teleport disabled' not in availability:
            raise ValueError('Unbuilt spawn must be explicitly disabled')
        rows.append(dict(id=spawn,district=district,plaza=plaza,x=x,surfaceY=y,z=z,
                         built=built,runtimeActive=False,primary=spawn=='SC-01',
                         availability=availability))
    if [r['id'] for r in rows]!=['SC-01','SC-02','SC-03','SC-04']:
        raise ValueError('Expected four stable spawn IDs in canonical order')
    required=['Historic Core (District A)','Harbour','Market','Cathedral Quarter']
    if [r['district'] for r in rows]!=required:
        raise ValueError('Canonical names changed; record Atlas ART-BIBLE objection before changing the ruling')
    ruling=json.loads((ROOT/'audit/spawn-anchor-ruling.json').read_text())
    if rows[0]['x']!=ruling['selected']['x'] or rows[0]['z']!=ruling['selected']['z']:
        raise ValueError('Primary spawn differs from recorded centroid/plaza ruling')
    data=dict(source='NAMES.md',authority='Manager A binding interim ruling',
              engineTested=False,minimumAcceptanceRouteStuds=1500,spawns=rows)
    lua=['--!strict','-- GENERATED by tools/walkaudit/names.py FROM root NAMES.md; do not edit by hand.',
         '-- Naming handoff only: no runtime SpawnLocations/teleports are created or enabled.',
         'return table.freeze({']
    for row in rows:
        lua.extend(['\ttable.freeze({',f'\t\tid = {json.dumps(row["id"])},',
            f'\t\tdistrict = {json.dumps(row["district"])},',f'\t\tplaza = {json.dumps(row["plaza"])},',
            f'\t\tx = {row["x"]:g},',f'\t\tsurfaceY = {row["surfaceY"]:g},',f'\t\tz = {row["z"]:g},',
            f'\t\tbuilt = {str(row["built"]).lower()},','\t\truntimeActive = false,',
            f'\t\tprimary = {str(row["primary"]).lower()},','\t}),'])
    lua.append('})')
    return {'src/server/Spawn/CanonicalPlan.luau':'\n'.join(lua)+'\n',
            'audit/canonical-spawns.json':json.dumps(data,indent=2)+'\n'}


def main():
    parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
    for name,content in outputs().items():
        path=ROOT/name
        if args.check:
            if not path.exists() or path.read_text()!=content:
                raise SystemExit('Canonical handoff drift: '+name+'; regenerate from NAMES.md')
        else:
            path.parent.mkdir(parents=True,exist_ok=True);path.write_text(content)
    print('Canonical names/anchors match NAMES.md; all runtime activations remain false')


if __name__=='__main__': main()
